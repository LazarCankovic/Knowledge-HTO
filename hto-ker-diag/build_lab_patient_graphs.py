"""Build joint patient diagnosis/lab graphs in the shared SNOMED graph.

    python build_lab_patient_graphs.py --dataset full --kg-tag lab_snomed \
    --mimic-dir /path/to/mimic_data

Requires final_labs.parquet regenerated by this branch's extraction notebook;
older charttime-based extracts are rejected via the time_source column.
"""
from __future__ import annotations

import argparse
import json
import pickle
import sys
import time
from dataclasses import fields
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT / "src"))

from hto.data.splits import load_split
from hto.kg.lab_graph import lab_code_key
from hto.kg.patient_graphs import PatientGraphConfig, build_all
from hto.kg.snomed_graph import load_graph


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dataset", required=True)
    ap.add_argument("--kg-tag", required=True)
    ap.add_argument("--mimic-dir", required=True)
    for f in fields(PatientGraphConfig):
        ap.add_argument(f"--{f.name.replace('_', '-')}", type=int, default=f.default)
    args = ap.parse_args()

    kg_dir = ROOT / "processed_data" / "kg" / args.kg_tag
    out_dir = ROOT / "processed_data" / args.dataset
    split = load_split(out_dir / "split.json")
    patient_ids = split["train_ids"] | split["val_ids"] | split["test_ids"]
    graph = load_graph(kg_dir)
    if not {"lab", "icd", "snomed"} <= set(graph["entities"]["kind"]):
        raise SystemExit(f"{kg_dir} needs linked lab, diagnosis, and SNOMED nodes")
    relation_names = set(graph["relations"]["name"])
    if "maps_lab_to_snomed" not in relation_names:
        raise SystemExit(f"{kg_dir} has no lab-to-SNOMED links")

    path = Path(args.mimic_dir).expanduser() / "final_labs.parquet"
    try:
        labs = pd.read_parquet(path, columns=["patient_id", "time", "time_source", "itemid"])
    except Exception as exc:
        raise SystemExit(f"Cannot read required lab columns from {path}: {exc}. "
                         "Rerun the storetime-based extraction if time_source is missing") from exc
    if set(labs["time_source"].dropna().unique()) != {"storetime"}:
        raise SystemExit(f"{path} must come from the storetime-based extraction; rerun extraction")
    labs = labs[labs["patient_id"].isin(patient_ids)].dropna(subset=["itemid"])
    labs = labs.assign(lab_code=labs["itemid"].map(lab_code_key))
    known = set(graph["entities"].loc[graph["entities"]["kind"] == "lab", "key"])
    code_coverage = float(labs["lab_code"].isin(known).mean()) if len(labs) else 0.0
    if code_coverage < 0.90:
        raise SystemExit(f"Only {code_coverage:.1%} of lab rows map to the graph; "
                         "check that d_labitems matches the extraction's MIMIC-IV release")
    rel_id = int(graph["relations"].loc[
        graph["relations"]["name"] == "maps_lab_to_snomed", "id"].iloc[0])
    linked_ids = set(graph["triples"].loc[graph["triples"]["r"] == rel_id, "h"])
    linked_keys = set(graph["entities"].loc[graph["entities"]["id"].isin(linked_ids), "key"])
    snomed_coverage = float(labs["lab_code"].isin(linked_keys).mean()) if len(labs) else 0.0
    if snomed_coverage == 0:
        raise SystemExit("No cohort lab rows connect to SNOMED; review itemid-to-LOINC mapping")

    diagnoses_path = Path(args.mimic_dir).expanduser() / "final_diagnoses.parquet"
    diagnoses = pd.read_parquet(diagnoses_path, columns=["patient_id", "time", "diag"])
    diagnoses = diagnoses[diagnoses["patient_id"].isin(patient_ids)].dropna(subset=["diag"])
    observed = pd.concat([
        labs[["patient_id", "time", "lab_code"]].rename(columns={"lab_code": "code"}),
        diagnoses[["patient_id", "time", "diag"]].rename(columns={"diag": "code"}),
    ], ignore_index=True)
    cfg = PatientGraphConfig(**{f.name: getattr(args, f.name) for f in fields(PatientGraphConfig)})
    started = time.time()
    graphs, stats = build_all(observed, graph, cfg, code_col="code", code_kind="mixed",
                              path_time_priority=True)
    stats.update(seconds=round(time.time() - started, 1), kg_tag=args.kg_tag,
                 time_source="storetime", domain="lab", lab_row_graph_coverage=code_coverage,
                 lab_row_snomed_coverage=snomed_coverage,
                 diagnosis_rows=int(len(diagnoses)), lab_rows=int(len(labs)))
    out_dir.mkdir(parents=True, exist_ok=True)
    out_path = out_dir / f"patient_graphs.{args.kg_tag}.pkl"
    with open(out_path, "wb") as f:
        pickle.dump({"domain": "lab", "kg_tag": args.kg_tag,
                     "n_entities": len(graph["entities"]), "n_relations": len(graph["relations"]),
                     "config": stats["config"], "graphs": graphs}, f)
    out_path.with_suffix(".stats.json").write_text(json.dumps(stats, indent=2))
    print(json.dumps(stats, indent=2))
    print(f"Wrote {out_path}")


if __name__ == "__main__":
    main()
